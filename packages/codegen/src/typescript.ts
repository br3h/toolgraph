/** `compile()` types its argument through `json-schema`, which we do not depend on. */
type CompilerSchema = Parameters<typeof compile>[0];

const BANNER = '/* Generated by toolgraph. Do not edit by hand. */';
const SDK_PACKAGE = '@modelcontextprotocol/sdk';
const CLIENT_IMPORT = `import type { Client } from '${SDK_PACKAGE}/client/index.js';`;

/** Deep enough for any hand-written tool schema; short enough to stay bounded. */
const MAX_SCHEMA_DEPTH = 12;

/* -------------------------------------------------------------------------- */
/* Names                                                                       */
/* -------------------------------------------------------------------------- */

interface ToolNames {
  inputType: string;
  outputType: string;
  schemaConst: string;
  fn: string;
}

/**
 * One name per tool per role, allocated once so `types.ts`, `schemas.ts`,
 * `client.ts` and `run.ts` cannot drift apart. Two servers exporting the same
 * tool name is normal, hence the dedupe.
 */
function allocateNames(tools: McpToolDescriptor[]): Map<McpToolDescriptor, ToolNames> {
  const types = new Set<string>(['GraphInput', 'GraphOutput']);
  const values = new Set<string>(['runGraph', 'client', 'input']);
  const names = new Map<McpToolDescriptor, ToolNames>();

  for (const tool of tools) {
    const pascal = toPascalCase(tool.name);
    const camel = toCamelCase(tool.name);
    names.set(tool, {
      inputType: uniqueName(`${pascal}Input`, types),
      outputType: uniqueName(`${pascal}Output`, types),
      fn: uniqueName(camel, values),
      schemaConst: uniqueName(`${camel}InputSchema`, values),
    });
  }
  return names;
}

function namesFor(names: Map<McpToolDescriptor, ToolNames>, tool: McpToolDescriptor): ToolNames {
  const found = names.get(tool);
  if (!found) throw new Error(`No generated name was allocated for the tool "${tool.name}".`);
  return found;
}

/** First occurrence wins, so the plan and the generator agree on object identity. */
function dedupeTools(tools: McpToolDescriptor[]): McpToolDescriptor[] {
  const seen = new Set<string>();
  const out: McpToolDescriptor[] = [];
  for (const tool of tools) {
    const key = `${tool.serverId} ${tool.name}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(tool);
  }
  return out;
}

