/**
 * Generate a standalone TypeScript bundle for `doc`.
 *
 * Async because json-schema-to-typescript is: it formats what it emits, and
 * doing that by hand would mean reimplementing an entire pretty-printer.
 */
export async function generateTypeScript(
  doc: ToolGraphDocument,
  tools: McpToolDescriptor[],
): Promise<CodegenResult> {
  const unique = dedupeTools(tools);
  const plan = planGraph(doc, unique);
  const warnings = [...plan.warnings];
  const names = allocateNames(unique);

  const takenKeys = new Set<string>();
  const inputKeys = new Map(
    plan.inputs.map((entry) => [entry.nodeId, uniqueName(toCamelCase(entry.label), takenKeys)]),
  );
  const outputKeys = new Map(
    plan.outputs.map((entry) => [entry.nodeId, uniqueName(toCamelCase(entry.label), takenKeys)]),
  );

  const files: GeneratedFile[] = [
    await typesFile(unique, names, plan, inputKeys, outputKeys, warnings),
    schemasFile(unique, names, warnings),
    clientFile(unique, names),
    runFile(plan, names, inputKeys, outputKeys, warnings),
    packageJsonFile(plan),
    readmeFile(plan, names),
  ];

  return { target: 'typescript', files, warnings };
}
