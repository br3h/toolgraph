/* Literals                                                                    */
/* -------------------------------------------------------------------------- */

/** A static input, rendered as TypeScript source. */
function tsLiteral(value: unknown, indent: string): string {
  if (value === null) return 'null';
  if (typeof value === 'string') return quoteTs(value);
  if (typeof value === 'boolean') return String(value);
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'undefined';
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const items = value.map((item) => `${indent}  ${tsLiteral(item, `${indent}  `)},`);
    return `[\n${items.join('\n')}\n${indent}]`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>);
    if (entries.length === 0) return '{}';
    const lines = entries.map(([key, item]) => {
      const token = isValidTsIdentifier(key) ? key : quoteTs(key);
      return `${indent}  ${token}: ${tsLiteral(item, `${indent}  `)},`;
    });
    return `{\n${lines.join('\n')}\n${indent}}`;
  }
  // `undefined`, and anything else JSON cannot carry, has no useful spelling.
  return 'undefined';
}

function renderTree(tree: ValueTree, indent: string, warnings: string[]): string {
  if (tree.kind === 'leaf') return tree.expr;
  const { children } = tree;
  if (children.size === 0) return '{}';

  if (isArrayBranch(children)) {
    const length = arrayBranchLength(children);
    const items: string[] = [];
    for (let index = 0; index < length; index += 1) {
      const child = children.get(String(index));
      if (child === undefined) {
        warnings.push(`Nothing feeds index ${index} of an array argument; it is left undefined.`);
        items.push(`${indent}  undefined as never,`);
        continue;
      }
      items.push(`${indent}  ${renderTree(child, `${indent}  `, warnings)},`);
    }
    return `[\n${items.join('\n')}\n${indent}]`;
  }

  const lines = [...children.entries()].map(([key, child]) => {
    const token = isValidTsIdentifier(key) ? key : quoteTs(key);
    return `${indent}  ${token}: ${renderTree(child, `${indent}  `, warnings)},`;
  });
  return `{\n${lines.join('\n')}\n${indent}}`;
}

