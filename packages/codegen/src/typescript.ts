interface ZodContext {
  root: JsonSchema;
  subject: string;
  warnings: string[];
}

function warnAt(ctx: ZodContext, pointer: string, problem: string): void {
  const where = pointer === '' ? 'its input' : `input field "${pointer}"`;
  ctx.warnings.push(`${ctx.subject}: ${where} ${problem}; the zod schema uses z.unknown() there.`);
}

/** A zod expression for `raw`. The first line is unindented; the rest sits under `indent`. */
function zodFor(
  raw: JsonSchema | undefined,
  pointer: string,
  ctx: ZodContext,
  indent: string,
  depth: number,
): string {
  if (depth > MAX_SCHEMA_DEPTH) {
    warnAt(ctx, pointer, 'nests deeper than the generator follows');
    return 'z.unknown()';
  }
  const schema = normalizeSchema(raw, ctx.root);
  if (!schema) {
    warnAt(ctx, pointer, 'could not be resolved');
    return 'z.unknown()';
  }

  if (schema.const !== undefined) {
    const literal = zodLiteral(schema.const);
    if (literal !== undefined) return literal;
    warnAt(ctx, pointer, 'is a const with a non-primitive value');
    return 'z.unknown()';
  }

  if (Array.isArray(schema.enum) && schema.enum.length > 0) {
    return zodEnum(schema.enum, pointer, ctx, indent);
  }

  const anyOf = Array.isArray(schema.anyOf) && schema.anyOf.length > 0 ? schema.anyOf : undefined;
  const oneOf = Array.isArray(schema.oneOf) && schema.oneOf.length > 0 ? schema.oneOf : undefined;
  const branches = anyOf ?? oneOf;
  if (branches) {
    if (!anyOf) {
      ctx.warnings.push(
        `${ctx.subject}: ${pointer === '' ? 'its input' : `input field "${pointer}"`} uses oneOf; the generated union accepts a value matching more than one branch.`,
      );
    }
    const members = branches.map((branch, index) =>
      zodFor(branch, `${pointer}/${index}`, ctx, `${indent}  `, depth + 1),
    );
    return renderUnion(members, indent);
  }

  const types = normalizeTypes(schema.type);
  if (types.length === 0) {
    const inferred = inferType(schema);
    if (inferred === undefined) {
      warnAt(ctx, pointer, 'declares no type');
      return 'z.unknown()';
    }
    return zodForType(inferred, schema, pointer, ctx, indent, depth);
  }
  if (types.length === 1 && types[0] !== undefined) {
    return zodForType(types[0], schema, pointer, ctx, indent, depth);
  }
  const members = types.map((type) =>
    zodForType(type, schema, pointer, ctx, `${indent}  `, depth + 1),
  );
  return renderUnion(members, indent);
}

/** A schema with no `type` still tells us what it is, if it has any structure. */
function inferType(schema: JsonSchema): JsonSchemaType | undefined {
  if (schema.properties || schema.required || schema.additionalProperties !== undefined) {
    return 'object';
  }
  if (schema.items || schema.prefixItems) return 'array';
  return undefined;
}

function zodForType(
  type: JsonSchemaType,
  schema: JsonSchema,
  pointer: string,
  ctx: ZodContext,
  indent: string,
  depth: number,
): string {
  switch (type) {
    case 'string':
      return 'z.string()';
    case 'number':
      return 'z.number()';
    case 'integer':
      return 'z.number().int()';
    case 'boolean':
      return 'z.boolean()';
    case 'null':
      return 'z.null()';
    case 'array':
      return zodArray(schema, pointer, ctx, indent, depth);
    case 'object':
      return zodObject(schema, pointer, ctx, indent, depth);
  }
}

function zodArray(
  schema: JsonSchema,
  pointer: string,
  ctx: ZodContext,
  indent: string,
  depth: number,
): string {
  if (Array.isArray(schema.prefixItems) && schema.prefixItems.length > 0) {
    const members = schema.prefixItems.map((item, index) =>
      zodFor(item, `${pointer}/${index}`, ctx, `${indent}  `, depth + 1),
    );
    return `z.tuple([\n${members.map((member) => `${indent}  ${member},`).join('\n')}\n${indent}])`;
  }
  if (!schema.items) {
    warnAt(ctx, `${pointer}/items`, 'has no item schema');
    return 'z.array(z.unknown())';
  }
  return `z.array(${zodFor(schema.items, `${pointer}/items`, ctx, indent, depth + 1)})`;
}

function zodObject(
  schema: JsonSchema,
  pointer: string,
  ctx: ZodContext,
  indent: string,
  depth: number,
): string {
  const properties = schema.properties ?? {};
  const keys = Object.keys(properties);
  const additional = schema.additionalProperties;

  if (keys.length === 0) {
    if (additional === false) return 'z.strictObject({})';
    if (isSchemaObject(additional)) {
      return `z.record(z.string(), ${zodFor(additional, `${pointer}/additionalProperties`, ctx, indent, depth + 1)})`;
    }
    return 'z.record(z.string(), z.unknown())';
  }

  const required = new Set(schema.required ?? []);
  const entries = keys.map((key) => {
    const value = zodFor(properties[key], `${pointer}/${key}`, ctx, `${indent}  `, depth + 1);
    const suffix = required.has(key) ? '' : '.optional()';
    const token = isValidTsIdentifier(key) ? key : quoteTs(key);
    return `${indent}  ${token}: ${value}${suffix},`;
  });

  const factory =
    additional === false
      ? 'z.strictObject'
      : additional === undefined
        ? 'z.object'
        : 'z.looseObject';
  if (isSchemaObject(additional)) {
    ctx.warnings.push(
      `${ctx.subject}: the object at "${pointer === '' ? '/' : pointer}" constrains its additional properties; the generated schema only allows them through.`,
    );
  }
  return `${factory}({\n${entries.join('\n')}\n${indent}})`;
}

function zodEnum(values: unknown[], pointer: string, ctx: ZodContext, indent: string): string {
  if (values.every((value) => typeof value === 'string')) {
    return `z.enum([${values.map((value) => quoteTs(value)).join(', ')}])`;
  }
  const members: string[] = [];
  for (const value of values) {
    const literal = zodLiteral(value);
    if (literal === undefined) {
      warnAt(ctx, pointer, 'is an enum containing a non-primitive value');
      return 'z.unknown()';
    }
    members.push(literal);
  }
  if (members.length === 1 && members[0] !== undefined) return members[0];
  return renderUnion(members, indent);
}

function zodLiteral(value: unknown): string | undefined {
  if (typeof value === 'string') return `z.literal(${quoteTs(value)})`;
  if (typeof value === 'boolean') return `z.literal(${String(value)})`;
  if (typeof value === 'number' && Number.isFinite(value)) return `z.literal(${String(value)})`;
  if (value === null) return 'z.null()';
  return undefined;
}

function renderUnion(members: string[], indent: string): string {
  if (members.length === 1 && members[0] !== undefined) return members[0];
  return `z.union([\n${members.map((member) => `${indent}  ${member},`).join('\n')}\n${indent}])`;
}

