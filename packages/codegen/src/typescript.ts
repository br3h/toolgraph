/**
 * The TypeScript export.
 *
 * The bundle this produces must keep working after toolgraph is deleted from
 * the user's machine, so the only imports it may emit are `zod` and the
 * official MCP SDK. Nothing here writes an import that points back at this
 * repository, and `typescript.test.ts` compiles the result to prove it.
 *
 * Node-only: `json-schema-to-typescript` pulls in Node built-ins.
 */

