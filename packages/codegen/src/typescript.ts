/* Schema preparation                                                          */
/* -------------------------------------------------------------------------- */

const SCHEMA_MAPS = ['properties', 'patternProperties', '$defs', 'definitions'] as const;
const SCHEMA_LISTS = ['anyOf', 'oneOf', 'allOf', 'prefixItems'] as const;
const SCHEMA_SLOTS = ['items', 'not', 'if', 'then', 'else', 'additionalProperties'] as const;

/** Visit every position that holds a schema, and no position that merely looks like one. */
function visitSchemas(schema: JsonSchema, visit: (node: JsonSchema) => void): void {
  const seen = new Set<JsonSchema>();
  const walk = (node: JsonSchema): void => {
    if (seen.has(node)) return;
    seen.add(node);
    visit(node);
    for (const key of SCHEMA_MAPS) {
      const map = node[key];
      if (!map || typeof map !== 'object') continue;
      for (const child of Object.values(map as Record<string, unknown>)) {
        if (isSchemaObject(child)) walk(child);
      }
    }
    for (const key of SCHEMA_LISTS) {
      const list = node[key];
      if (!Array.isArray(list)) continue;
      for (const child of list) if (isSchemaObject(child)) walk(child);
    }
    for (const key of SCHEMA_SLOTS) {
      const child = node[key];
      if (isSchemaObject(child)) walk(child);
    }
  };
  walk(schema);
}

function isSchemaObject(value: unknown): value is JsonSchema {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Strip `title` and `$id` from every schema in the document.
 *
 * json-schema-to-typescript names a declaration after its `title` when it has
 * one, in preference to the name we pass. Two tools that both call a field
 * "Result" would then emit two `export interface Result` declarations into one
 * file. Dropping the annotation makes the naming ours, and so predictable.
 */
function stripDeclarationNames(schema: JsonSchema): void {
  visitSchemas(schema, (node) => {
    delete node.title;
    delete node.$id;
    delete node.$schema;
  });
}

interface NamespacedSchema {
  schema: JsonSchema;
  defs: Record<string, JsonSchema>;
}

/**
 * Lift a schema's own `$defs` into a prefixed, shareable namespace.
 *
 * Definitions become top-level interfaces, so `Item` from one tool and `Item`
 * from another would collide in `types.ts`. Renaming them up front — and
 * rewriting the `$ref`s that point at them — keeps every declaration unique
 * without any string surgery on the generated output.
 */
function namespaceDefs(source: JsonSchema, prefix: string): NamespacedSchema {
  const schema = structuredClone(source);
  const defs: Record<string, JsonSchema> = {};
  const mapping = new Map<string, string>();

  for (const container of ['$defs', 'definitions'] as const) {
    const original = schema[container];
    if (!original || typeof original !== 'object') continue;
    for (const [key, value] of Object.entries(original)) {
      const renamed = `${prefix}${toPascalCase(key)}`;
      mapping.set(`#/${container}/${key}`, `#/$defs/${renamed}`);
      defs[renamed] = value;
    }
    delete schema[container];
  }

  if (mapping.size > 0) rewriteRefs(schema, mapping);
  for (const def of Object.values(defs)) rewriteRefs(def, mapping);

  return { schema, defs };
}

/** Rewrite `$ref` strings, including refs that address a path inside a definition. */
function rewriteRefs(node: unknown, mapping: ReadonlyMap<string, string>): void {
  if (Array.isArray(node)) {
    for (const item of node) rewriteRefs(item, mapping);
    return;
  }
  if (typeof node !== 'object' || node === null) return;
  const record = node as Record<string, unknown>;
  const ref = record.$ref;
  if (typeof ref === 'string') {
    for (const [from, to] of mapping) {
      if (ref === from) {
        record.$ref = to;
        break;
      }
      if (ref.startsWith(`${from}/`)) {
        record.$ref = `${to}${ref.slice(from.length)}`;
        break;
      }
    }
  }
  for (const value of Object.values(record)) rewriteRefs(value, mapping);
}

/** Assemble one self-contained document jstt can compile on its own. */
function documentFor(schema: JsonSchema, typeName: string): JsonSchema {
  const { schema: body, defs } = namespaceDefs(schema, typeName);
  stripDeclarationNames(body);
  for (const def of Object.values(defs)) stripDeclarationNames(def);
  return Object.keys(defs).length > 0 ? { ...body, $defs: defs } : body;
}

async function compileType(
  schema: JsonSchema,
  typeName: string,
  subject: string,
  warnings: string[],
): Promise<string> {
  try {
    const output = await compile(
      documentFor(schema, typeName) as unknown as CompilerSchema,
      typeName,
      {
        bannerComment: '',
        additionalProperties: false,
      },
    );
    return output.trim();
  } catch (error) {
    warnings.push(
      `${subject} could not be turned into a TypeScript type (${describeError(error)}); it is typed as unknown.`,
    );
    return `export type ${typeName} = unknown;`;
  }
}

function describeError(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

