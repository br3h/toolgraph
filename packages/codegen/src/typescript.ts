async function typesFile(
  tools: McpToolDescriptor[],
  names: Map<McpToolDescriptor, ToolNames>,
  plan: GraphPlan,
  inputKeys: Map<string, string>,
  outputKeys: Map<string, string>,
  warnings: string[],
): Promise<GeneratedFile> {
  const blocks: string[] = [];

  for (const tool of tools) {
    const { inputType, outputType } = namesFor(names, tool);
    blocks.push(
      await compileType(tool.inputSchema, inputType, `The input of "${tool.name}"`, warnings),
    );
    if (tool.outputSchema) {
      blocks.push(
        await compileType(tool.outputSchema, outputType, `The output of "${tool.name}"`, warnings),
      );
    } else {
      blocks.push(
        `/** \`${tool.name}\` declares no output schema, so its result cannot be typed. */\nexport type ${outputType} = unknown;`,
      );
    }
  }

  blocks.push(
    await compileType(
      boundarySchema(
        plan.inputs.map((entry) => ({
          key: keyFor(inputKeys, entry.nodeId),
          schema: entry.schema,
        })),
      ),
      'GraphInput',
      'The graph input',
      warnings,
    ),
  );
  blocks.push(
    await compileType(
      boundarySchema(
        plan.outputs.map((entry) => ({
          key: keyFor(outputKeys, entry.nodeId),
          schema: entry.schema,
        })),
      ),
      'GraphOutput',
      'The graph output',
      warnings,
    ),
  );

  return {
    path: 'types.ts',
    contents: `${BANNER}\n\n${blocks.join('\n\n')}\n`,
  };
}

/** One object with a property per boundary node, so 0, 1 and many all read alike. */
function boundarySchema(entries: Array<{ key: string; schema: JsonSchema }>): JsonSchema {
  const properties: Record<string, JsonSchema> = {};
  for (const entry of entries) properties[entry.key] = entry.schema;
  return {
    type: 'object',
    additionalProperties: false,
    properties,
    required: entries.map((entry) => entry.key),
  };
}

function keyFor(keys: Map<string, string>, nodeId: string): string {
  const key = keys.get(nodeId);
  if (key === undefined) throw new Error(`No generated key was allocated for node "${nodeId}".`);
  return key;
}

function schemasFile(
  tools: McpToolDescriptor[],
  names: Map<McpToolDescriptor, ToolNames>,
  warnings: string[],
): GeneratedFile {
  const blocks = tools.map((tool) => {
    const { schemaConst } = namesFor(names, tool);
    const ctx: ZodContext = { root: tool.inputSchema, subject: tool.name, warnings };
    const expression = zodFor(tool.inputSchema, '', ctx, '', 0);
    return `/** Runtime validation for the \`${tool.name}\` tool input. */\nexport const ${schemaConst} = ${expression};`;
  });

  const body = blocks.length > 0 ? blocks.join('\n\n') : '// This graph references no tools.';
  return {
    path: 'schemas.ts',
    contents: `${BANNER}\n\nimport { z } from 'zod';\n\n${body}\n`,
  };
}

function clientFile(
  tools: McpToolDescriptor[],
  names: Map<McpToolDescriptor, ToolNames>,
): GeneratedFile {
  const typeImports: string[] = [];
  const schemaImports: string[] = [];
  const functions: string[] = [];

  for (const tool of tools) {
    const { inputType, outputType, schemaConst, fn } = namesFor(names, tool);
    typeImports.push(inputType, outputType);
    schemaImports.push(schemaConst);
    const doc = tool.description ? `\n * ${tool.description.replace(/\s+/g, ' ').trim()}` : '';
    functions.push(
      `/**\n * Call the \`${tool.name}\` tool.${doc}\n */\n` +
        `export async function ${fn}(client: Client, input: ${inputType}): Promise<${outputType}> {\n` +
        `  const args = ${schemaConst}.parse(input);\n` +
        `  return callTool<${outputType}>(client, ${quoteTs(tool.name)}, args);\n` +
        `}`,
    );
  }

  const imports = [CLIENT_IMPORT];
  if (schemaImports.length > 0) {
    imports.push(`import { ${schemaImports.join(', ')} } from './schemas.js';`);
    imports.push(`import type { ${typeImports.join(', ')} } from './types.js';`);
  }

  const helpers = `/**
 * Unwrap an MCP tool result.
 *
 * Servers may answer with \`structuredContent\`, or with a text block holding
 * JSON, or with plain prose. All three are accepted, in that order.
 */
async function callTool<T>(client: Client, name: string, args: unknown): Promise<T> {
  const result = await client.callTool({ name, arguments: args as Record<string, unknown> });
  if (result.isError === true) {
    throw new Error(\`The MCP tool \${name} reported an error: \${firstText(result.content) ?? 'no details'}\`);
  }
  if (result.structuredContent !== undefined) {
    return result.structuredContent as T;
  }
  const text = firstText(result.content);
  if (text === undefined) {
    return undefined as T;
  }
  try {
    return JSON.parse(text) as T;
  } catch {
    return text as T;
  }
}

function firstText(content: unknown): string | undefined {
  if (!Array.isArray(content)) return undefined;
  for (const block of content as Array<{ type?: unknown; text?: unknown }>) {
    if (block.type === 'text' && typeof block.text === 'string') return block.text;
  }
  return undefined;
}`;

  const body = functions.length > 0 ? `${helpers}\n\n${functions.join('\n\n')}` : helpers;
  return {
    path: 'client.ts',
    contents: `${BANNER}\n\n${imports.join('\n')}\n\n${body}\n`,
  };
}

function runFile(
  plan: GraphPlan,
  names: Map<McpToolDescriptor, ToolNames>,
  inputKeys: Map<string, string>,
  outputKeys: Map<string, string>,
  warnings: string[],
): GeneratedFile {
  const usedFunctions: string[] = [];
  const usedTypes = new Set<string>(['GraphInput', 'GraphOutput']);
  const taken = new Set<string>(['client', 'input', 'runGraph']);
  for (const tool of plan.usedTools) {
    const { fn } = namesFor(names, tool);
    usedFunctions.push(fn);
    taken.add(fn);
  }

  const variables = new Map<string, string>();
  const statements: string[] = [];

  for (const step of plan.steps) {
    const { inputType, fn } = namesFor(names, step.tool);
    usedTypes.add(inputType);
    const base = toCamelCase(step.label);
    const argsName = uniqueName(`${base}Args`, taken);
    const resultName = uniqueName(`${base}Result`, taken);
    variables.set(step.nodeId, resultName);

    const { tree, warnings: treeWarnings } = buildValueTree(
      step.assignments.map((assignment) => ({
        pointer: assignment.pointer,
        expr: expressionFor(assignment, plan, variables, inputKeys, warnings),
      })),
    );
    for (const warning of treeWarnings) warnings.push(`${step.label}: ${warning}`);

    const value = tree === undefined ? '{}' : renderTree(tree, '  ', warnings);
    statements.push(`  const ${argsName}: ${inputType} = ${value};`);
    statements.push(`  const ${resultName} = await ${fn}(client, ${argsName});`);
    statements.push('');
  }

  const returnEntries = plan.outputs.map((output) => {
    const { tree, warnings: treeWarnings } = buildValueTree(
      output.assignments.map((assignment) => ({
        pointer: assignment.pointer,
        expr: expressionFor(assignment, plan, variables, inputKeys, warnings),
      })),
    );
    for (const warning of treeWarnings) warnings.push(`${output.label}: ${warning}`);
    const value = tree === undefined ? '{}' : renderTree(tree, '    ', warnings);
    return `    ${keyFor(outputKeys, output.nodeId)}: ${value},`;
  });

  const returnStatement =
    returnEntries.length > 0 ? `  return {\n${returnEntries.join('\n')}\n  };` : '  return {};';

  const imports = [CLIENT_IMPORT];
  if (usedFunctions.length > 0) {
    imports.push(`import { ${usedFunctions.join(', ')} } from './client.js';`);
  }
  imports.push(`import type { ${[...usedTypes].join(', ')} } from './types.js';`);

  const body = [...statements, returnStatement].join('\n');
  const contents =
    `${BANNER}\n\n${imports.join('\n')}\n\n` +
    `/**\n * Run the ${quoteTs(plan.name)} graph, one tool at a time, in dependency order.\n */\n` +
    `export async function runGraph(client: Client, input: GraphInput): Promise<GraphOutput> {\n` +
    `${body}\n}\n`;

  return { path: 'run.ts', contents };
}

function expressionFor(
  assignment: Assignment,
  plan: GraphPlan,
  variables: ReadonlyMap<string, string>,
  inputKeys: ReadonlyMap<string, string>,
  warnings: string[],
): string {
  if (assignment.kind === 'static') return tsLiteral(assignment.value, '  ');

  const inputKey = inputKeys.get(assignment.sourceNodeId);
  if (inputKey !== undefined) {
    return `input.${inputKey}${pointerToAccessPath(assignment.sourceHandle, 'ts')}`;
  }
  const variable = variables.get(assignment.sourceNodeId);
  if (variable === undefined) {
    // Only reachable if the plan is inconsistent with itself; say so rather
    // than emit a reference to a variable that does not exist.
    throw new Error(
      `Node "${assignment.sourceNodeId}" feeds another node but produces no value in "${plan.name}".`,
    );
  }
  void warnings;
  return `${variable}${pointerToAccessPath(assignment.sourceHandle, 'ts')}`;
}

function packageJsonFile(plan: GraphPlan): GeneratedFile {
  const manifest = {
    name: packageSlug(plan.name),
    version: '0.1.0',
    private: true,
    description: `Generated MCP client for the ${plan.name} graph.`,
    type: 'module',
    dependencies: {
      [SDK_PACKAGE]: '^1.20.0',
      zod: '^4.0.0',
    },
  };
  return { path: 'package.json', contents: `${JSON.stringify(manifest, null, 2)}\n` };
}

function packageSlug(name: string): string {
  const slug = toSnakeCase(name)
    .replace(/_/g, '-')
    .replace(/^-+|-+$/g, '');
  return slug.length > 0 ? slug : 'mcp-graph-export';
}

